-- Additive private backend schema. Existing public project tables are preserved.

CREATE SCHEMA atm;

REVOKE ALL ON SCHEMA atm FROM PUBLIC, anon, authenticated, service_role;

CREATE ROLE atm_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;

GRANT USAGE ON SCHEMA atm TO atm_runtime;


CREATE TABLE atm.audit_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	team VARCHAR(64) NOT NULL, 
	actor VARCHAR(100) NOT NULL, 
	kind VARCHAR(60) NOT NULL, 
	object_id VARCHAR(100) NOT NULL, 
	request_id VARCHAR(36) NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	PRIMARY KEY (id)
)

;

CREATE INDEX ix_audit_team_cursor ON atm.audit_events (team, id);

ALTER TABLE atm.audit_events ENABLE ROW LEVEL SECURITY;

CREATE POLICY backend_only ON atm.audit_events TO atm_runtime USING (true) WITH CHECK (true);


CREATE TABLE atm.jobs (
	id UUID NOT NULL, 
	team VARCHAR(64) NOT NULL, 
	kind VARCHAR(30) NOT NULL, 
	object_id UUID NOT NULL, 
	state VARCHAR(20) NOT NULL, 
	attempts INTEGER NOT NULL, 
	available_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	error_code VARCHAR(50), 
	PRIMARY KEY (id), 
	UNIQUE (kind, object_id), 
	CHECK (state IN ('PENDING','DONE','FAILED'))
)

;

CREATE INDEX ix_atm_jobs_team ON atm.jobs (team);

CREATE INDEX ix_jobs_available ON atm.jobs (available_at, id) WHERE state = 'PENDING';

ALTER TABLE atm.jobs ENABLE ROW LEVEL SECURITY;

CREATE POLICY backend_only ON atm.jobs TO atm_runtime USING (true) WITH CHECK (true);


