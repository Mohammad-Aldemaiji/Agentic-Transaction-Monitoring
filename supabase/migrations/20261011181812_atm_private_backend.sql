CREATE TABLE atm.transactions (
	id UUID NOT NULL, 
	team VARCHAR(64) NOT NULL, 
	external_id VARCHAR(100) NOT NULL, 
	idempotency_key VARCHAR(100) NOT NULL, 
	payload_hash VARCHAR(64) NOT NULL, 
	account_id VARCHAR(100) NOT NULL, 
	amount_minor BIGINT NOT NULL, 
	currency VARCHAR(3) NOT NULL, 
	occurred_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	received_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	channel VARCHAR(20) NOT NULL, 
	status VARCHAR(20) NOT NULL, 
	result JSONB, 
	PRIMARY KEY (id), 
	UNIQUE (team, external_id), 
	UNIQUE (team, idempotency_key), 
	CHECK (amount_minor > 0 AND amount_minor <= 1000000000000), 
	CHECK (currency ~ '^[A-Z]{3}$'), 
	CHECK (status IN ('PENDING','SCORED','FAILED'))
)

;

CREATE INDEX ix_transaction_history ON atm.transactions (team, account_id, occurred_at, id);

ALTER TABLE atm.transactions ENABLE ROW LEVEL SECURITY;

CREATE POLICY backend_only ON atm.transactions TO atm_runtime USING (true) WITH CHECK (true);


