CREATE FUNCTION atm.reject_evidence_mutation() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$ BEGIN RAISE EXCEPTION 'Evidence records are append only'; END; $$;

REVOKE ALL ON FUNCTION atm.reject_evidence_mutation() FROM PUBLIC;

CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON atm.audit_events FOR EACH ROW EXECUTE FUNCTION atm.reject_evidence_mutation();

CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON atm.case_events FOR EACH ROW EXECUTE FUNCTION atm.reject_evidence_mutation();

CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON atm.decisions FOR EACH ROW EXECUTE FUNCTION atm.reject_evidence_mutation();

CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON atm.executions FOR EACH ROW EXECUTE FUNCTION atm.reject_evidence_mutation();

CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON atm.call_turns FOR EACH ROW EXECUTE FUNCTION atm.reject_evidence_mutation();

